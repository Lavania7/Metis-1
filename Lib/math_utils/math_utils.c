/**
 * @brief 对称限幅函数 输出范围：[-limit, +limit]
 * 
 * @param x 输入值
 * @param limit 正限幅值
 * @return float 输出结果
 */
float clamp(float x, float limit)
{
    if (x > limit) return limit;
    if (x < -limit) return -limit;
    return x;
}



